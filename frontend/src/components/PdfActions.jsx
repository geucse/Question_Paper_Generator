import { useEffect, useState } from 'react';
import { api } from '../api';

// Download, preview and print one paper PDF (the token cannot go in a plain link, so the PDF is fetched as a blob).
// Preview and print ask for ?inline=1 (Content-Disposition inline, audited as a view); preview shows it in a frame
// on the page, print hands it to the browser's print dialog. run: useAsync().run, so failures show on the screen.
export default function PdfActions({ token, path, filename, label = 'PDF', title, run }) {
  const [previewUrl, setPreviewUrl] = useState(null);
  useEffect(() => () => { if (previewUrl) URL.revokeObjectURL(previewUrl); }, [previewUrl]);
  const inlinePath = `${path}${path.includes('?') ? '&' : '?'}inline=1`;

  async function preview() {
    const blob = await run(() => api.get(inlinePath, token));
    if (blob) setPreviewUrl(URL.createObjectURL(blob));
  }

  async function print() {
    const blob = await run(() => api.get(inlinePath, token));
    if (!blob) return;
    const url = URL.createObjectURL(blob);
    const frame = document.createElement('iframe');
    frame.style.display = 'none';
    frame.title = `${label} for printing`;
    frame.src = url;
    frame.onload = () => {
      try { frame.contentWindow.focus(); frame.contentWindow.print(); } catch { window.open(url, '_blank', 'noopener'); }
      setTimeout(() => { frame.remove(); URL.revokeObjectURL(url); }, 60000);
    };
    document.body.appendChild(frame);
  }

  return (
    <div className="paper-output-row">
      <span className="what">{title || label.charAt(0).toUpperCase() + label.slice(1)}</span>
      <button className="btn-primary btn-sm" onClick={() => run(() => api.download(path, token, filename))}>Download {label}</button>
      <button className="btn-ghost btn-sm" aria-expanded={!!previewUrl} onClick={previewUrl ? () => setPreviewUrl(null) : preview}>{previewUrl ? `Close ${label} preview` : `Preview ${label}`}</button>
      <button className="btn-ghost btn-sm" onClick={print}>Print {label}</button>
      {previewUrl && <div className="pdf-sheet" style={{ flexBasis: '100%' }}><iframe className="pdf-frame" title={`${label} preview`} src={previewUrl} /></div>}
    </div>
  );
}

// The printed paper's output actions: the formal examination paper generated by the server (backend/src/paper-pdf.js).
// Preview, download and print use the same PDF, so what is previewed is exactly what is printed.
export function PaperOutput({ status, children }) {
  return (
    <section className="paper-output" aria-label="Printed paper">
      <div className="paper-output-head">
        <h4>Printed paper</h4>
        <span className="hint" style={{ margin: 0 }}>
          {status === 'PRINT_READY' ? 'Final: locked for printing.' : 'Not print-ready yet: every page carries a DRAFT watermark.'} The preview is the same PDF that downloads and prints.
        </span>
      </div>
      {children}
    </section>
  );
}
