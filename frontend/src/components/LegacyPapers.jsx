import { useEffect, useState } from 'react';
import { api } from '../api';
import { Messages } from './ui';
import { useAsync } from '../lib/useAsync';
import PdfActions from './PdfActions';
import { typeLabel } from '../lib/questionTypes';

// Pre-pivot papers (before the examination domain) of departments the HOD covers, read-only (GET /api/papers):
// rendered from their frozen snapshots; rebuilt snapshots are flagged. Examination papers belong to the COE.
export default function LegacyPapers({ token }) {
  const [rows, setRows] = useState(null);
  const [open, setOpen] = useState(null);
  const [detail, setDetail] = useState(null);
  const { error, run } = useAsync();
  useEffect(() => { run(async () => setRows(await api.get('/papers', token))); }, [token, run]);

  async function show(id) {
    if (open === id) { setOpen(null); setDetail(null); return; }
    setOpen(id); setDetail(null);
    await run(async () => setDetail(await api.get(`/papers/${id}`, token)));
  }

  return (
    <div>
      <h3 className="section-title">Legacy papers</h3>
      <p className="hint">Papers made before the examination workflow, kept as they were printed. Read-only; new papers are generated by the COE.</p>
      <Messages error={error} reasons={[]} ok="" />
      {rows === null && !error && <p className="hint" role="status">Loading…</p>}
      {rows?.length === 0 && <div className="empty-state">No legacy papers in your department.</div>}
      {(rows || []).map((p) => (
        <div key={p.id} className="list-item" style={{ display: 'block' }}>
          <div className="row" style={{ justifyContent: 'space-between' }}>
            <div><strong>{p.title || 'Untitled paper'}</strong> <span className="hint">{p.status}{p.locked_at ? ` · locked ${new Date(p.locked_at).toLocaleDateString()}` : ''} · {new Date(p.created_at).toLocaleDateString()}</span></div>
            <button className="btn-ghost btn-sm" style={{ flex: 'none' }} onClick={() => show(p.id)}>{open === p.id ? 'Close' : 'Open'}</button>
          </div>
          {open === p.id && detail && (
            <div style={{ marginTop: 8 }}>
              <PdfActions token={token} run={run} path={`/papers/${p.id}/pdf`} filename={`legacy-paper-${p.id.slice(0, 8)}.pdf`} label="PDF" />
              <PdfActions token={token} run={run} path={`/papers/${p.id}/pdf?include_answers=1`} filename={`legacy-paper-${p.id.slice(0, 8)}-answers.pdf`} label="PDF with answers" />
              {detail.questions.length === 0 && <p className="hint">No questions recorded for this paper.</p>}
              {detail.questions.map((q, i) => (
                <div key={q.id || i} className="list-item" style={{ display: 'block' }}>
                  <strong>Q{i + 1}.</strong> {q.snapshot_missing ? <em className="hint">(no snapshot was recorded for this question)</em> : q.question_text}
                  <div className="hint">{typeLabel(q.question_type)} · {q.difficulty || '—'} · {q.marks ?? '—'} marks{q.topic ? ` · ${q.topic}` : ''}{q.reconstructed ? ' · rebuilt from the question bank (migration 040)' : ''}</div>
                </div>
              ))}
            </div>
          )}
        </div>
      ))}
    </div>
  );
}
